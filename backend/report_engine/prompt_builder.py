    @staticmethod
    def _fmt(val) -> str:
        if val is None:
            return "N/A"
        if isinstance(val, float):
            return f"{val:.2f}"
        return str(val)

    @staticmethod
    def _format_reasons(reasons: list) -> str:
        """格式化信号原因列表"""
        if not reasons:
            return "无"
        formatted = []
        for r in reasons:
            if isinstance(r, dict):
                indicator = r.get("indicator", "")
                detail = r.get("detail", "")
                formatted.append(f"{indicator}: {detail}" if indicator else str(r))
            else:
                formatted.append(str(r))
        return "; ".join(formatted)
