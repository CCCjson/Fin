        if finnhub:
            parts.append("\n【International Markets (English)】")
            for n in finnhub:
                src = f"[{n['source']}] " if n.get("source") else ""
                time_str = f" ({n['time']})" if n.get("time") else ""
                sent = _sent_tag(n)
                sent_str = f" [{sent}]" if sent else ""
                parts.append(f"  {idx}. {src}{n['title']}{time_str}{sent_str}")
                if n.get("body"):
                    parts.append(f"     {n['body']}")
                idx += 1

        # 持仓个股相关新闻（简要，点到为止）
