    @staticmethod
    def _format_indicator_snapshot(indicators: dict) -> str:
        """格式化技术指标快照为可读文本"""
        if not indicators:
            return ""

        def _v(key: str, fmt: str = ".2f") -> str:
            val = indicators.get(key)
            if val is None:
                return "N/A"
            return f"{val:{fmt}}"

        lines = ["技术指标快照:"]

        # 均线
        lines.append(
            f"  均线: MA5={_v('ma5')}, MA10={_v('ma10')}, MA20={_v('ma20')} "
            f"[{indicators.get('ma_status', 'N/A')}]"
        )

        # MACD
        lines.append(
            f"  MACD: DIF={_v('macd_dif', '.4f')}, DEA={_v('macd_dea', '.4f')}, "
            f"柱={_v('macd_bar', '.4f')} [{indicators.get('macd_position', 'N/A')}]"
        )

        # RSI
        lines.append(
            f"  RSI: {_v('rsi')} [{indicators.get('rsi_zone', 'N/A')}]"
        )

        # KDJ
        lines.append(
            f"  KDJ: K={_v('kdj_k')}, D={_v('kdj_d')}, J={_v('kdj_j')}"
        )

        # 布林带
        lines.append(
            f"  布林带: 上轨={_v('boll_upper')}, 中轨={_v('boll_middle')}, "
            f"下轨={_v('boll_lower')} [{indicators.get('boll_position', 'N/A')}]"
        )

        # 量比
        vr = indicators.get('volume_ratio')
        vr_str = f"{vr:.2f}" if vr is not None else "N/A"
        vr_desc = indicators.get('volume_ratio_desc', '')
        lines.append(f"  量比: {vr_str} ({vr_desc})")

        # ATR
        atr = indicators.get('atr')
        atr_str = f"{atr:.2f}" if atr is not None else "N/A"
        lines.append(f"  ATR(14): {atr_str}")

        return "\n".join(lines)

